use acadrust::tables::{
    normalize_name, LineTypeComplexContent, LineTypeComplexData, LineTypeElement,
};
use acadrust::{CadDocument, DxfReader, DxfWriter, Layer, LineType};
use std::fmt::Write;

pub fn generate_map(path: &str) -> acadrust::Result<()> {
    let mut output = String::from("// SPDX-License-Identifier: MPL-2.0\n// Generated by tests/upstream generate-name-map using acadrust normalize_name.\n");
    writeln!(
        output,
        "// Rust Unicode {:?}; regenerate with the same Rust toolchain.",
        char::UNICODE_VERSION
    )
    .unwrap();
    output.push_str("constexpr std::pair<char32_t, char32_t> name_uppercase[] = {\n");
    for c in (0..=0x10ffff).filter_map(char::from_u32) {
        let normalized = normalize_name(&c.to_string());
        let upper = normalized.chars().next().unwrap();
        if c != upper {
            writeln!(output, "    {{0x{:X}, 0x{:X}}},", c as u32, upper as u32).unwrap();
        }
    }
    output.push_str("};\n");
    std::fs::write(path, output)?;
    Ok(())
}

pub fn generate(ascii: &str, binary: &str) -> acadrust::Result<()> {
    let mut doc = CadDocument::new();
    for name in ["建筑A", "Notes", "Étage", "straße", "Ｓ", "ſ"] {
        doc.layers.add(Layer::new(name))?;
    }
    let mut pattern = LineType::new("中心线A");
    pattern.description = "长划 点 间隔".into();
    pattern.elements = vec![
        LineTypeElement::dash(2.),
        LineTypeElement::space(0.5),
        LineTypeElement::dot(),
        LineTypeElement::space(0.5),
    ];
    pattern.pattern_length = 3.;
    doc.line_types.add(pattern)?;
    let mut complex = LineType::new("文字线");
    complex.description = "文字与形状".into();
    complex.pattern_length = 2.;
    complex.elements = vec![
        LineTypeElement {
            length: 1.,
            complex: Some(LineTypeComplexData {
                content: LineTypeComplexContent::Text {
                    text: "给水".into(),
                },
                style_handle: doc.text_styles.get("Standard").unwrap().handle,
                scale: 0.5,
                rotation: std::f64::consts::FRAC_PI_2,
                offset: [0.25, -0.5],
                absolute_rotation: true,
                ..Default::default()
            }),
        },
        LineTypeElement {
            length: -1.,
            complex: Some(LineTypeComplexData {
                content: LineTypeComplexContent::Shape { shape_number: 7 },
                style_handle: doc.text_styles.get("Standard").unwrap().handle,
                scale: 2.,
                upright: true,
                ..Default::default()
            }),
        },
    ];
    doc.line_types.add(complex)?;
    DxfWriter::new(&doc).write_to_file(ascii)?;
    DxfWriter::new_binary(&doc).write_to_file(binary)
}

fn close(value: &str, expected: f64) {
    let actual: f64 = value.parse().unwrap();
    assert!((actual - expected).abs() <= 1e-12, "{actual} != {expected}");
}
pub fn verify(drawing: &str, result: &str) -> acadrust::Result<()> {
    let doc = DxfReader::from_file(drawing)?.read()?;
    let cpp = std::fs::read_to_string(result)?;
    let mut lines = cpp.lines();
    let mut queries = 0;
    while let Some(line) = lines.next() {
        queries += 1;
        let f: Vec<_> = line.split('\t').collect();
        if f[0] == "L" {
            match doc.layers.get(f[1]) {
                None => assert_eq!(f.len(), 2),
                Some(layer) => {
                    assert_eq!(f.len(), 4);
                    assert_eq!(f[2], layer.name);
                    assert_eq!(u64::from_str_radix(f[3], 16).unwrap(), layer.handle.value());
                }
            }
        } else {
            assert_eq!(f[0], "T");
            let Some(lt) = doc.line_types.get(f[1]) else {
                assert_eq!(f.len(), 2);
                continue;
            };
            assert_eq!(f.len(), 8);
            assert_eq!(f[2], lt.name);
            assert_eq!(u64::from_str_radix(f[3], 16).unwrap(), lt.handle.value());
            assert_eq!(f[4], lt.description);
            close(f[5], lt.pattern_length);
            assert_eq!(f[6], if lt.xref_dependent { "1" } else { "0" });
            assert_eq!(f[7].parse::<usize>().unwrap(), lt.elements.len());
            for e in &lt.elements {
                let values: Vec<_> = lines.next().unwrap().split('\t').collect();
                assert_eq!(values[0], "E");
                close(values[1], e.length);
                if let Some(c) = &e.complex {
                    assert_eq!(values.len(), 12);
                    match &c.content {
                        LineTypeComplexContent::Text { text } => {
                            assert_eq!(values[2], "text");
                            assert_eq!(values[3], text);
                        }
                        LineTypeComplexContent::Shape { shape_number } => {
                            assert_eq!(values[2], "shape");
                            assert_eq!(values[3].parse::<i16>().unwrap(), *shape_number);
                        }
                    }
                    assert_eq!(values[4].parse::<u64>().unwrap(), c.style_handle.value());
                    close(values[5], c.scale);
                    close(values[6], c.rotation);
                    close(values[7], c.offset[0]);
                    close(values[8], c.offset[1]);
                    assert_eq!(values[9], if c.absolute_rotation { "1" } else { "0" });
                    assert_eq!(values[10], if c.upright { "1" } else { "0" });
                    assert_eq!(values[11].parse::<u8>().unwrap(), c.source_flags);
                } else {
                    assert_eq!(values.len(), 2);
                }
            }
        }
    }
    assert_eq!(queries, 18);
    Ok(())
}
